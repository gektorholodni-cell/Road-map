const pad = (n: number) => String(n).padStart(2, '0');

export function buildSeedProject(now = new Date().toISOString()): Project {
  const islands: Island[] = [];
  const tasks: Record<string, Task> = {};
  const letters = ['a', 'b', 'c', 'd', 'e', 'f'];

  ISLANDS.forEach((spec, ii) => {
    const islandId = `i${ii + 1}`;
    let n = 0;
    const chapters: Chapter[] = spec.chapters.map((cs, ci) => {
      const chapterId = `${islandId}-c${letters[ci]}`;
      return {
        id: chapterId,
        title: cs.title,
        description: cs.description,
        stages: cs.stages.map((ss, si) => {
          const stageId = `${chapterId}-s${si + 1}`;
          const taskIds: string[] = [];
          ss.tasks.forEach((ts) => {
            n += 1;
            const id = `${islandId}-t${pad(n)}`;
            taskIds.push(id);
            tasks[id] = {
              id,
              islandId,
              chapterId,
              stageId,
              title: ts.title,
              description: ts.description,
              criteria: ts.criteria,
              status: 'todo',
              priority: ts.priority ?? 'medium',
              required: !ts.optional,
              dependsOn: (ts.deps ?? []).map((d) => (typeof d === 'number' ? `${islandId}-t${pad(d)}` : d)),
              achievementIds: [],
              notes: '',
              createdAt: now,
              subtasks: [],
            };
          });
          return { id: stageId, title: ss.title, taskIds };
        }),
      };
    });
    islands.push({
      id: islandId,
      name: spec.name,
      subtitle: spec.subtitle,
      description: spec.description,
      theme: spec.theme,
      completionCriteria: spec.completionCriteria,
      chapters,
      unlockRule: 'sequential',
      manuallyUnlocked: false,
      unlockedAt: ii === 0 ? now : undefined,
      map: { ...spec.map },
    });
  });

  // Пример подзадач, чтобы механика была видна сразу.
  tasks['i1-t01'].subtasks = [
    { id: 'i1-t01-st1', title: 'Записать 5 вариантов формулировки', done: false },
    { id: 'i1-t01-st2', title: 'Выбрать лучший вариант', done: false },
    { id: 'i1-t01-st3', title: 'Проверить на постороннем человеке', done: false },
  ];

  return {
    app: APP_ID,
    schemaVersion: SCHEMA_VERSION,
    id: `project-${Date.now().toString(36)}`,
    name: 'Моя игра',
    createdAt: now,
    updatedAt: now,
    islands,
    tasks,
    achievements: BUILTIN_ACHIEVEMENTS.map((a) => ({ ...a })),
    unlocked: {},
    stats: { reopened: {} },
    settings: { soundEnabled: false, reducedMotion: 'auto', allowManualUnlock: false, showMinimap: true },
    session: { view: 'map', heroPos: {} },
  };
}
